-- cost_classifications mirrors the contract_types policy set verbatim (baseline :7706 insert,
-- :7883 update, :8069 select, :8613 delete). Note contract_types matches on lower(users.role)
-- while project_phases matches on the exact-case role -- each table below keeps the convention
-- of the table it is modelled on rather than inventing a third.

CREATE POLICY "Authenticated users can view cost classifications"
  ON public.cost_classifications FOR SELECT TO authenticated USING (true);

CREATE POLICY "Authenticated users can insert cost classifications"
  ON public.cost_classifications FOR INSERT TO authenticated
  WITH CHECK ((EXISTS ( SELECT 1
     FROM public.users
    WHERE ((users.auth_user_id = auth.uid()) AND (lower(users.role) = ANY (ARRAY['director'::text, 'admin'::text, 'project_manager'::text, 'supervision'::text]))))));

CREATE POLICY "Authenticated users can update cost classifications"
  ON public.cost_classifications FOR UPDATE TO authenticated
  USING ((EXISTS ( SELECT 1
     FROM public.users
    WHERE ((users.auth_user_id = auth.uid()) AND (lower(users.role) = ANY (ARRAY['director'::text, 'admin'::text, 'project_manager'::text, 'supervision'::text]))))))
  WITH CHECK ((EXISTS ( SELECT 1
     FROM public.users
    WHERE ((users.auth_user_id = auth.uid()) AND (lower(users.role) = ANY (ARRAY['director'::text, 'admin'::text, 'project_manager'::text, 'supervision'::text]))))));

CREATE POLICY "Directors can delete cost classifications"
  ON public.cost_classifications FOR DELETE TO authenticated
  USING ((EXISTS ( SELECT 1
     FROM public.users
    WHERE ((users.auth_user_id = auth.uid()) AND (lower(users.role) = ANY (ARRAY['director'::text, 'admin'::text]))))));

-- phase_classification_budgets mirrors the project_phases policy set (baseline :8366 insert,
-- :8384 update, :8514 delete, :8586 select, :9146 Supervision-scoped select), reaching the
-- project through project_phases.
--
-- NOTE: project_phases itself has no SELECT policy for Supervision users on projects they do
-- not manage, and its write policies are role-only rather than project-scoped. That is mirrored
-- here exactly rather than silently tightened; fixing both is a separate, deliberate change.

CREATE POLICY "Directors and general users can view all phase classification budgets"
  ON public.phase_classification_budgets FOR SELECT TO authenticated
  USING ((EXISTS ( SELECT 1
     FROM public.users
    WHERE ((users.auth_user_id = auth.uid()) AND (users.role = ANY (ARRAY['Director'::text, 'Investment'::text, 'Sales'::text, 'Accounting'::text]))))));

CREATE POLICY "Supervision users can view phase classification budgets from assigned projects"
  ON public.phase_classification_budgets FOR SELECT TO authenticated
  USING ((EXISTS ( SELECT 1
     FROM ((public.project_phases ph
       JOIN public.project_managers pm ON ((pm.project_id = ph.project_id)))
       JOIN public.users u ON ((pm.user_id = u.id)))
    WHERE ((ph.id = phase_classification_budgets.phase_id) AND (u.auth_user_id = auth.uid()) AND (u.role = 'Supervision'::text)))));

CREATE POLICY "Director and Supervision can insert phase classification budgets"
  ON public.phase_classification_budgets FOR INSERT TO authenticated
  WITH CHECK ((EXISTS ( SELECT 1
     FROM public.users
    WHERE ((users.auth_user_id = auth.uid()) AND (users.role = ANY (ARRAY['Director'::text, 'Supervision'::text]))))));

CREATE POLICY "Director and Supervision can update phase classification budgets"
  ON public.phase_classification_budgets FOR UPDATE TO authenticated
  USING ((EXISTS ( SELECT 1
     FROM public.users
    WHERE ((users.auth_user_id = auth.uid()) AND (users.role = ANY (ARRAY['Director'::text, 'Supervision'::text]))))))
  WITH CHECK ((EXISTS ( SELECT 1
     FROM public.users
    WHERE ((users.auth_user_id = auth.uid()) AND (users.role = ANY (ARRAY['Director'::text, 'Supervision'::text]))))));

CREATE POLICY "Director and Supervision can delete phase classification budgets"
  ON public.phase_classification_budgets FOR DELETE TO authenticated
  USING ((EXISTS ( SELECT 1
     FROM public.users
    WHERE ((users.auth_user_id = auth.uid()) AND (users.role = ANY (ARRAY['Director'::text, 'Supervision'::text]))))));
