-- Splits the conflated `project_phases.phase_name` field into two independent axes:
--
--   * project_phases.phase_name  -> a REAL phase name ("Faza 1", "Foundation Phase")
--   * cost_classifications       -> the cost breakdown bucket a contract belongs to
--                                   ("Zemljiste", "Priprema i razvoj", ...)
--
-- Until now users typed the cost classification into `phase_name`, which meant a project
-- could never have more than one real phase and the seven canonical bucket names drifted
-- into 17 distinct spellings (casing, word order, synonyms, stray whitespace).
--
-- `contracts.contract_type_id` is UNAFFECTED and stays as a third, orthogonal axis
-- underneath the classification (Razno / Rusenje / Javni biljeznici).
--
-- The data migration that folds today's classification-shaped phase rows into this model
-- is 20260908120200_split_phase_classification.sql. Apply both together.

-- ---------------------------------------------------------------- cost_classifications

CREATE TABLE public.cost_classifications (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text UNIQUE,
    name        text NOT NULL UNIQUE,
    description text,
    sort_order  integer NOT NULL DEFAULT 0,
    is_system   boolean NOT NULL DEFAULT false,
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT cost_classifications_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT cost_classifications_system_has_code CHECK (NOT is_system OR code IS NOT NULL)
);

COMMENT ON TABLE public.cost_classifications IS
  'Global cost breakdown categories used to group contracts inside a project phase. '
  'is_system rows are seeded and may not be renamed or deleted. Orthogonal to contract_types.';
COMMENT ON COLUMN public.cost_classifications.code IS
  'Stable slug for seeded rows; NULL for user-created rows. Never shown to users -- it exists '
  'so migrations, assertions and tests can reference a bucket without a Croatian display string.';

-- integer identity PK deliberately mirrors contract_types (see 20260616120100), so the two
-- lookups stay structurally identical in the TS types and the two form selects.

CREATE TRIGGER update_cost_classifications_updated_at
