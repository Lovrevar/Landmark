-- Freeze the system rows in the DATABASE, not just the UI. RLS cannot express "this column
-- of this row is frozen", so without this trigger the guarantee is one `disabled` attribute
-- in React. is_active / sort_order / description stay editable so a company that never buys
-- land can hide "Zemljište" without deleting it.
CREATE OR REPLACE FUNCTION public.protect_system_cost_classifications()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.is_system THEN
      RAISE EXCEPTION 'Sistemska klasifikacija troška se ne može obrisati'
        USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN OLD;
  END IF;

  IF OLD.is_system AND (NEW.name      <>         OLD.name
                     OR NEW.code      IS DISTINCT FROM OLD.code
                     OR NEW.is_system <>         OLD.is_system) THEN
    RAISE EXCEPTION 'Sistemska klasifikacija troška se ne može preimenovati'
      USING ERRCODE = 'restrict_violation';
  END IF;

  RETURN NEW;
END $$;

CREATE TRIGGER trg_protect_system_cost_classifications
    BEFORE UPDATE OR DELETE ON public.cost_classifications
    FOR EACH ROW EXECUTE FUNCTION public.protect_system_cost_classifications();

-- ------------------------------------------------------------ contracts.classification_id

-- NULLABLE on purpose: Samobor's 5 and Tar's 32 contracts sit on phases whose names are real
-- phase names ("Foundation Phase", "Retroaktivno"), not classifications, so they legitimately
-- have no bucket. Repeating contract_type_id's `NOT NULL DEFAULT 0 -> nonexistent row` mistake
-- (fixed in 20260908120300) would be a regression.
--
-- No ON DELETE clause => NO ACTION, mirroring contracts_contract_type_id_fkey: a classification
-- that is in use cannot be deleted, users deactivate it instead.
ALTER TABLE public.contracts
    ADD COLUMN classification_id integer REFERENCES public.cost_classifications(id);

CREATE INDEX idx_contracts_classification_id
    ON public.contracts USING btree (classification_id);
CREATE INDEX idx_contracts_phase_classification
    ON public.contracts USING btree (phase_id, classification_id);

COMMENT ON COLUMN public.contracts.classification_id IS
  'Cost breakdown bucket within the phase. Orthogonal to contract_type_id. '
  'NULL means unclassified (legacy rows, or phases that are not cost-broken-down).';

-- ------------------------------------------------- phase_classification_budgets

-- Optional sub-allocation of a phase budget across classifications.
--
-- A row may exist with budget_allocated = 0 purely to pin an (empty) classification group into
-- a phase card -- that is how a user plans before any contract exists, and Funtana already does
-- exactly this (Opremanje budgeted at 812.401 with zero contracts).
--
-- Surrogate uuid PK rather than a composite (phase_id, classification_id) PK because
-- activity_logs.entity_id is uuid: with a composite key every budget edit would become a
-- metadata-only log entry, the same wart cost/contract type creation already has.
CREATE TABLE public.phase_classification_budgets (
    id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    phase_id          uuid NOT NULL REFERENCES public.project_phases(id) ON DELETE CASCADE,
    classification_id integer NOT NULL REFERENCES public.cost_classifications(id),
    budget_allocated  numeric(15,2) NOT NULL DEFAULT 0,
    notes             text,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT phase_classification_budgets_phase_classification_key
        UNIQUE (phase_id, classification_id),
    CONSTRAINT phase_classification_budgets_non_negative
        CHECK (budget_allocated >= 0)
);

CREATE INDEX idx_phase_classification_budgets_phase_id
    ON public.phase_classification_budgets USING btree (phase_id);

COMMENT ON TABLE public.phase_classification_budgets IS
  'Optional sub-allocation of project_phases.budget_allocated across cost classifications. '
  'The sum is intentionally NOT constrained to equal the phase budget -- sub-allocations are '
  'optional, so an unallocated remainder is a legitimate state, surfaced in the UI as '
  '"Neraspoređeno". A CHECK here would make the 20260908120200 data migration fail on the '
  'even-split budgets that most projects currently carry.';

CREATE TRIGGER update_phase_classification_budgets_updated_at
    BEFORE UPDATE ON public.phase_classification_budgets
    FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

